-- ####################CÁC LỆNH TRUY VẤN CƠ BẢN######################
-- HIỂN THỊ THÔNG TIN TỪ TABLE CỤ THỂ
SELECT * FROM EMPLOYEES;

-- HIỂN THỊ THÔNG TIN TỪ TABLE CÓ SẮP XẾP TĂNG DÂN ORDER B Y, VÀ GIỚI HẠN 10 DÒNG ĐẦU TIÊN ALTER
SELECT * FROM EMPLOYEES ORDER BY SALARY FETCH FIRST 10 ROWS ONLY;

-- HIỂN THỊ THÔNG TIN TỪ TABLE CÓ WITH TIES GIÚP LẤ CẢ GIÁ TRỊ TRÙNG LẶP GIỐNG NHAU
SELECT * FROM EMPLOYEES FETCH FIRST 10 ROWS WITH TIES;

-- SAO CHÉP BACKUP VALUE TỪ TABLE CHÍNH SANG TABLE MỚI MUỐN TẠO MÀ LẤY DỮ LIỆU TỪ TABLE CŨ
CREATE TABLE SUB_EMPL AS SELECT * FROM EMPLOYEES;
SELECT * FROM SUB_EMPL;

-- cách nối chũi hiển thị trong oracle: DÙNG DẤU ||
SELECT FIRST_NAME || ' ' || LAST_NAME AS FULLNAME FROM EMPLOYEES;

-- nếu muốn hiển thị 10 dòng trong table nào đó ở oracle thi cú pháp sau: chú ý với FETCH FIRST  VÀ ONLY
SELECT * FROM EMPLOYEES FETCH FIRST 10 ROWS ONLY;

-- sắp xếp value trong table tăng dần hiển thị 10 dòng đầu thui: ORDER BY(TĂNG DẦN) - ORDER BY DESK(giảm dần)
SELECT * FROM EMPLOYEES ORDER BY SALARY FETCH FIRST 10 ROWS ONLY;

-- cách sao chép value từ table trc đó sang table mới(thay vì insert value lại thì copy lấy value từ table đó đem qua luôn)
CREATE TABLE BACKUP_EMPLOYEES AS SELECT * FROM EMPLOYEES;
SELECT * FROM BACKUP_EMPLOYEES;




-- ######################## TRUY VẤN ĐIỀU KIỆN ##############################
-- DIEU KIEN VOI WHERE
SELECT * FROM EMPLOYEES;
SELECT FIRST_NAME || ' ' || LAST_NAME AS FULLNAME, PHONE_NUMBER, JOB_ID, SALARY FROM EMPLOYEES WHERE SALARY > 10000;

-- DIEU KIEN PHU DINH VOI NO(LOAI TRU CAI DO RA CON LAI DIEU HIEN THI)
SELECT FIRST_NAME || ' ' || LAST_NAME AS FULLNAME, PHONE_NUMBER, JOB_ID, SALARY FROM EMPLOYEES WHERE NOT SALARY = 6000;

-- DIEU KIEN KHOANG VOI BETWEEN ... AND
SELECT FIRST_NAME || ' ' || LAST_NAME AS FULLNAME, PHONE_NUMBER, JOB_ID, SALARY FROM EMPLOYEES WHERE SALARY BETWEEN 10000 AND 20000;

-- ĐIỀU KIỆN VỚI IN: GIÚP LỌC DỮ LIỆU CỦA TẬP HỢP MỘT LOẠT DANH SÁCH 
select * from countries;
SELECT * FROM COUNTRIES WHERE COUNTRY_ID IN ('IT', 'CA', 'JP', 'IN');

